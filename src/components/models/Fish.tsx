const BLINK_DURATION = 0.15

const _gaze = new Vector3()

export default function Fish({
  colorA = 'white',
  colorB = 'white',
  colorC = 'white',
  castShadow = false,
  hooked = false,
  ...props
}: FishProps) {
  const { nodes, materials } = useGLTF('./models/fish.glb') as GLTFResult
  const face = useMemo(() => getFace(nodes.Iris_Color_0.geometry), [nodes])
  const body = useMemo(() => getBody(nodes), [nodes])

  const bodyMaterial = useMemo(
    () => createBodyMaterial(materials.Color, [colorA, colorB, colorC]),
    [materials, colorA, colorB, colorC],
  )

  const eyes = [useRef<Group>(null!), useRef<Group>(null!)]
  const pupils = [useRef<Mesh>(null!), useRef<Mesh>(null!)]
  const mouth = useRef<Group>(null!)

  // Each fish keeps its own rhythm
  const phase = useMemo(() => random(0, 10), [])
  const gulpFrequency = useMemo(() => random(0.25, 0.5), [])
  const nextBlink = useRef(0)
  const nextGaze = useRef(0)
  const gaze = useRef({ x: 0, z: 0 })
  const gazeTarget = useRef({ x: 0, z: 0 })
  const fright = useRef(0)

  useFrame(({ clock }, delta) => {
    const t = clock.elapsedTime + phase
    fright.current = MathUtils.damp(fright.current, hooked ? 1 : 0, 10, delta)

    // Blink: squash the eyes down, once in a while twice in a row. Not with popping eyes
    if (t > nextBlink.current + BLINK_DURATION) {
      nextBlink.current = t + (Math.random() < 0.2 ? 0.1 : random(2, 5))
    }
    const blinkTime = t - nextBlink.current
    const blink =
      !hooked && blinkTime > 0 && blinkTime < BLINK_DURATION
        ? Math.sin((blinkTime / BLINK_DURATION) * Math.PI)
        : 0

    // Look around, faster and more nervously when hooked
    if (t > nextGaze.current) {
      const range = hooked ? 0.5 : 0.4
      const centered = !hooked && Math.random() < 0.3
      gazeTarget.current.x = centered ? 0 : random(-range, range)
      gazeTarget.current.z = centered ? 0 : random(-range, range)
      nextGaze.current = t + (hooked ? random(0.15, 0.4) : random(0.8, 2.5))
    }
    const gazeSpeed = hooked ? 25 : 12
    gaze.current.x = MathUtils.damp(gaze.current.x, gazeTarget.current.x, gazeSpeed, delta)
    gaze.current.z = MathUtils.damp(gaze.current.z, gazeTarget.current.z, gazeSpeed, delta)

    // Hooked, eyes grow upwards (not to cover the mouth) and pop out forward, as the pivot is
    // the eyeball center. Pupils grow too
    const wide = 1 + fright.current * 0.2
    const pop = 1 + fright.current * 0.3
    const pupilSize = 1 + fright.current * 0.5

    for (let i = 0; i < 2; i++) {
      const eye = face.eyes[i]
      eyes[i].current.scale.set(wide, pop, wide * (1 - blink * 0.85))
      eyes[i].current.position.setZ(eye.center.z + eye.size.z * (wide - 1) * 0.5)

      // Pupils slide over the eyeball, compensating its scale
      const { x, z } = gaze.current
      const slope = face.slopes[i]
      pupils[i].current.scale.set(pupilSize / wide, pupilSize / pop, pupilSize / wide)
      pupils[i].current.position
        .subVectors(face.pupils[i].center, eye.center)
        .add(_gaze.set(x, slope.x * x + slope.y * z, z))
    }

    // Mouth: a "blub" now and then, opening downwards (not to cover the eyes).
    // Hooked, it stays small and puckered around the hook, keeping its depth not to sink in the head
    const cycle = (t * gulpFrequency) % 1
    const gulp = cycle < 0.25 ? Math.sin((cycle / 0.25) * Math.PI) ** 2 : 0
    const open = gulp * (1 - fright.current)
    const stretch = open * 0.4
    const shrink = 1 - fright.current * 0.45
    mouth.current.scale.set((1 - open * 0.15) * shrink, 1 + open * 0.2, (1 + stretch) * shrink)
    mouth.current.position.setZ(face.mouth.center.z - face.mouth.size.z * stretch * 0.5)
  })

  return (
    <group {...props} dispose={null}>
      <group rotation={[-Math.PI / 2, 0, 0]} scale={0.001}>
        <group rotation={[Math.PI / 2, 0, 0]}>
          <mesh castShadow={castShadow} geometry={body} material={bodyMaterial} />
          <group
            position={[0, 240.885, 158.506]}
            rotation={[-1.679, 0, 0]}
            scale={[12.905, 7.823, 15.739]}
          >
            {face.eyes.map((eye, i) => (
              <group key={i} ref={eyes[i]} position={eye.center}>
                <mesh geometry={eye.geometry} material={materials.Color} />
                <mesh
                  ref={pupils[i]}
                  geometry={face.pupils[i].geometry}
                  material={materials.Color}
                />
              </group>
            ))}
            <group ref={mouth} position={face.mouth.center}>
              <mesh geometry={face.mouth.geometry} material={materials.Color} />
            </group>
          </group>
        </group>
      </group>
    </group>
  )
}

